// Р’РёР·СѓР°Р»РёР·Р°С†РёСЏ e-graph'Р°.
//
// egg СѓРјРµРµС‚ РІС‹РіСЂСѓР¶Р°С‚СЊ e-graph РІ С„РѕСЂРјР°С‚ GraphViz DOT (egraph.dot()).
// Р•СЃР»Рё РЅР° РјР°С€РёРЅРµ РµСЃС‚СЊ Р±РёРЅР°СЂРЅРёРє `dot` (Graphviz), РјС‹ РґРѕРїРѕР»РЅРёС‚РµР»СЊРЅРѕ СЂРµРЅРґРµСЂРёРј
// SVG/PNG РєР°СЂС‚РёРЅРєРё РІ РїР°РїРєСѓ `viz/`.
//
// РџРѕРёСЃРє `dot`:
//   1. РїРµСЂРµРјРµРЅРЅР°СЏ РѕРєСЂСѓР¶РµРЅРёСЏ GRAPHVIZ_DOT;
//   2. РїРµСЂРµРјРµРЅРЅР°СЏ РѕРєСЂСѓР¶РµРЅРёСЏ GRAPHVIZ_BIN;
//   3. Р±РёРЅР°СЂРЅРёРє `dot` РёР· PATH.
// ============================================================================

use egg::{Analysis, EGraph, Language};
use std::fmt::Display;
use std::path::{Path, PathBuf};
use std::process::Command;

/// РџР°РїРєР°, РєСѓРґР° СЃРєР»Р°РґС‹РІР°СЋС‚СЃСЏ С„Р°Р№Р»С‹ РІРёР·СѓР°Р»РёР·Р°С†РёРё (РІСЃРµРіРґР° СЂСЏРґРѕРј СЃ РїСЂРѕРµРєС‚РѕРј,
/// РЅРµР·Р°РІРёСЃРёРјРѕ РѕС‚ С‚РѕРіРѕ, РѕС‚РєСѓРґР° Р·Р°РїСѓС‰РµРЅР° РїСЂРѕРіСЂР°РјРјР°).
const VIZ_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/viz");

fn dot_binary() -> Option<PathBuf> {
    for var in ["GRAPHVIZ_DOT", "GRAPHVIZ_BIN"] {
        if let Ok(p) = std::env::var(var) {
            let path = PathBuf::from(p);
            let candidate = if path.is_dir() {
                path.join("dot.exe")
            } else {
                path
            };
            if candidate.exists() {
                return Some(candidate);
            }
        }
    }
    if let Ok(which) = Command::new("dot").arg("-V").output() {
        if which.status.success() {
            return Some(PathBuf::from("dot"));
        }
    }
    None
}

/// РЎРѕС…СЂР°РЅСЏРµС‚ .dot С„Р°Р№Р» Рё, РµСЃР»Рё РґРѕСЃС‚СѓРїРµРЅ Graphviz, С‚Р°РєР¶Рµ SVG Рё PNG.
fn dump<L, N>(egraph: &EGraph<L, N>, name: &str)
where
    L: Language + Display,
    N: Analysis<L>,
{
    let dir = Path::new(VIZ_DIR);
    if !dir.exists() {
        std::fs::create_dir_all(dir).expect("РЅРµ СѓРґР°Р»РѕСЃСЊ СЃРѕР·РґР°С‚СЊ РїР°РїРєСѓ viz/");
    }

    let dot_path = dir.join(format!("{name}.dot"));
    egraph
        .dot()
        .to_dot(&dot_path)
        .expect("РЅРµ СѓРґР°Р»РѕСЃСЊ СЃРѕС…СЂР°РЅРёС‚СЊ .dot С„Р°Р№Р»");
    println!("  СЃРѕС…СЂР°РЅС‘РЅ: {} ({} Р±Р°Р№С‚)", dot_path.display(), dot_path.metadata().map(|m| m.len()).unwrap_or(0));

    match dot_binary() {
        Some(bin) => {
            let svg = dir.join(format!("{name}.svg"));
            let png = dir.join(format!("{name}.png"));
            match egraph.dot().run(&bin, ["-Tsvg", "-o", svg.to_str().unwrap()]) {
                Ok(()) => println!("  СЂРµРЅРґРµСЂ:  {}", svg.display()),
                Err(e) => println!("  РѕС€РёР±РєР° СЂРµРЅРґРµСЂР° SVG: {e}"),
            }
            match egraph.dot().run(&bin, ["-Tpng", "-o", png.to_str().unwrap()]) {
                Ok(()) => println!("  СЂРµРЅРґРµСЂ:  {}", png.display()),
                Err(e) => println!("  РѕС€РёР±РєР° СЂРµРЅРґРµСЂР° PNG: {e}"),
            }
        }
        None => println!("  (Graphviz РЅРµ РЅР°Р№РґРµРЅ вЂ” СЃРјРѕС‚СЂРёС‚Рµ {name}.dot РЅР°РїСЂСЏРјСѓСЋ РёР»Рё СѓСЃС‚Р°РЅРѕРІРёС‚Рµ Graphviz)"),
    }
}
