// РљРѕСЂРѕС‚РєРѕ РїСЂРѕ РёРґРµСЋ:
//   1. Р’С‹СЂР°Р¶РµРЅРёСЏ С…СЂР°РЅСЏС‚СЃСЏ РІ РІРёРґРµ РіСЂР°С„Р°, РіРґРµ РѕРґРёРЅР°РєРѕРІС‹Рµ РїРѕРґРІС‹СЂР°Р¶РµРЅРёСЏ
//      РїСЂРµРґСЃС‚Р°РІР»РµРЅС‹ РѕРґРЅРёРј СѓР·Р»РѕРј (РєР»Р°СЃСЃ СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕСЃС‚Рё, "e-class").
//   2. РџСЂР°РІРёР»Р° РїРµСЂРµРїРёСЃС‹РІР°РЅРёСЏ РїСЂРёРјРµРЅСЏСЋС‚СЃСЏ РќР• РєР°Рє РІ РѕР±С‹С‡РЅРѕРј С‚РµСЂРј-СЂР°Р№С‚РµСЂРµ
//      (РєРѕС‚РѕСЂС‹Р№ РїРµСЂРµРїРёСЃС‹РІР°РµС‚ Рё РІС‹Р±СЂР°СЃС‹РІР°РµС‚ СЃС‚Р°СЂРѕРµ), Р° РїСЂРѕСЃС‚Рѕ Р”РћР‘РђР’Р›РЇР®Рў
//      СЂР°РІРµРЅСЃС‚РІР° РјРµР¶РґСѓ СѓР·Р»Р°РјРё. РџРѕСЌС‚РѕРјСѓ РЅРё РѕРґРЅРѕ СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕРµ РІС‹СЂР°Р¶РµРЅРёРµ
//      РЅРµ С‚РµСЂСЏРµС‚СЃСЏ. Р­С‚Рѕ РЅР°Р·С‹РІР°РµС‚СЃСЏ "equality saturation".
//   3. Р’ РєРѕРЅС†Рµ РёР· РіСЂР°С„Р° РёР·РІР»РµРєР°РµС‚СЃСЏ Р»СѓС‡С€РµРµ РІС‹СЂР°Р¶РµРЅРёРµ РїРѕ Р·Р°РґР°РЅРЅРѕР№ СЃС‚РѕРёРјРѕСЃС‚Рё.
// ============================================================================

use egg::{rewrite as rw, *};

fn main() {
    println!("Р’РёР·СѓР°Р»РёР·Р°С†РёРё Р±СѓРґСѓС‚ СЃРѕС…СЂР°РЅРµРЅС‹ РІ РїР°РїРєСѓ egg-demo/viz/\n");
    part1_congruence_closure();
    part2_equality_saturation();
}

// --- Р§Р°СЃС‚СЊ 1: РєРѕРЅРіСЂСѓСЌРЅС‚РЅРѕРµ Р·Р°РјС‹РєР°РЅРёРµ (СЏРґСЂРѕ e-graph) --------------------------
fn part1_congruence_closure() {
    println!("=== Р§Р°СЃС‚СЊ 1: РєРѕРЅРіСЂСѓСЌРЅС‚РЅРѕРµ Р·Р°РјС‹РєР°РЅРёРµ ===\n");

    // EGraph РїР°СЂР°РјРµС‚СЂРёР·РѕРІР°РЅ СЏР·С‹РєРѕРј (SymbolLang вЂ” СЏР·С‹Рє "РїСЂРѕСЃС‚Рѕ СЃС‚СЂРѕРєРё")
    // Рё Р°РЅР°Р»РёР·РѕРј (Р·РґРµСЃСЊ РїСѓСЃС‚РѕР№ Р°РЅР°Р»РёР· вЂ” ()).
    let mut eg: EGraph<SymbolLang, ()> = Default::default();

    // Р”РѕР±Р°РІР»СЏРµРј Р»РёСЃС‚СЊСЏ a, b, c Рё СѓР·Р»С‹ f(a,b), f(a,c).
    // РљР°Р¶РґРѕРµ РґРѕР±Р°РІР»РµРЅРёРµ РІРѕР·РІСЂР°С‰Р°РµС‚ Id вЂ” СЃСЃС‹Р»РєСѓ РЅР° РєР»Р°СЃСЃ СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕСЃС‚Рё.
    let a = eg.add(SymbolLang::leaf("a"));
    let b = eg.add(SymbolLang::leaf("b"));
    let c = eg.add(SymbolLang::leaf("c"));
    let f_ab = eg.add(SymbolLang::new("f", vec![a, b]));
    let f_ac = eg.add(SymbolLang::new("f", vec![a, c]));
    eg.rebuild(); // РїРµСЂРµСЃС‡РёС‚Р°С‚СЊ РєР»Р°СЃСЃС‹ РїРѕСЃР»Рµ РёР·РјРµРЅРµРЅРёР№

    println!(
        "f(a,b) Рё f(a,c) РІ РѕРґРЅРѕРј РєР»Р°СЃСЃРµ? {}",
        eg.find(f_ab) == eg.find(f_ac)
    );
    println!("РЎРЅРёРјРѕРє РіСЂР°С„Р° РґРѕ РѕР±СЉСЏРІР»РµРЅРёСЏ СЂР°РІРµРЅСЃС‚РІ:");
    dump(&eg, "part1_before");

    // РћР±СЉСЏРІР»СЏРµРј СЂР°РІРµРЅСЃС‚РІР°: a = b Рё b = c.
    eg.union(a, b);
    eg.union(b, c);
    eg.rebuild();

    println!(
        "РџРѕСЃР»Рµ a=b, b=c: f(a,b) Рё f(a,c) РІ РѕРґРЅРѕРј РєР»Р°СЃСЃРµ? {}",
        eg.find(f_ab) == eg.find(f_ac)
    );
    println!("Р’СЃРµРіРѕ РєР»Р°СЃСЃРѕРІ СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕСЃС‚Рё: {}", eg.number_of_classes());
    println!("РЎРЅРёРјРѕРє РіСЂР°С„Р° РїРѕСЃР»Рµ РѕР±СЉСЏРІР»РµРЅРёСЏ СЂР°РІРµРЅСЃС‚РІ:");
    dump(&eg, "part1_after");
    println!();
}

// --- Р§Р°СЃС‚СЊ 2: equality saturation СЃ Runner'РѕРј --------------------------------
fn part2_equality_saturation() {
    println!("=== Р§Р°СЃС‚СЊ 2: equality saturation ===\n");

    // РџСЂР°РІРёР»Р° РїРµСЂРµРїРёСЃС‹РІР°РЅРёСЏ: "РёРјСЏ"; "Р»РµРІР°СЏ С‡Р°СЃС‚СЊ" => "РїСЂР°РІР°СЏ С‡Р°СЃС‚СЊ".
    // РџРµСЂРµРјРµРЅРЅС‹Рµ РЅР°С‡РёРЅР°СЋС‚СЃСЏ СЃ ? Рё РјР°С‚С‡Р°С‚СЃСЏ РЅР° С‡С‚Рѕ СѓРіРѕРґРЅРѕ.
    let rules: &[Rewrite<SymbolLang, ()>] = &[
        rw!("commute-add"; "(+ ?x ?y)" => "(+ ?y ?x)"),
        rw!("commute-mul"; "(* ?x ?y)" => "(* ?y ?x)"),
        rw!("add-0"; "(+ ?x 0)" => "?x"),
        rw!("mul-0"; "(* ?x 0)" => "0"),
        rw!("mul-1"; "(* ?x 1)" => "?x"),
        rw!("add-same"; "(+ ?x ?x)" => "(* 2 ?x)"),
        rw!("mul-assoc"; "(* (* ?x ?y) ?z)" => "(* ?x (* ?y ?z))"),
    ];

    // Р’С‹СЂР°Р¶РµРЅРёСЏ РїРёС€СѓС‚СЃСЏ РІ РїСЂРµС„РёРєСЃРЅРѕР№ (s-РІС‹СЂР°Р¶РµРЅРёСЏ) РЅРѕС‚Р°С†РёРё.
    let start: RecExpr<SymbolLang> = "(* (+ 0 (* 1 a)) (+ b b))".parse().unwrap();

    // РЎРЅРёРјРѕРє РіСЂР°С„Р° РґРѕ РїСЂРёРјРµРЅРµРЅРёСЏ РїСЂР°РІРёР» (РїСЂРѕСЃС‚Рѕ РёСЃС…РѕРґРЅРѕРµ РІС‹СЂР°Р¶РµРЅРёРµ).
    let mut egraph0: EGraph<SymbolLang, ()> = Default::default();
    egraph0.add_expr(&start);
    egraph0.rebuild();
    println!("РЎРЅРёРјРѕРє РіСЂР°С„Р° РґРѕ РїСЂРёРјРµРЅРµРЅРёСЏ РїСЂР°РІРёР»:");
    dump(&egraph0, "part2_start");

    // РџСЂРѕРјРµР¶СѓС‚РѕС‡РЅС‹Р№ СЃРЅРёРјРѕРє РїРѕСЃР»Рµ 2 РёС‚РµСЂР°С†РёР№ РїСЂР°РІРёР».
    let after2 = Runner::default()
        .with_expr(&start)
        .with_iter_limit(2)
        .run(rules);
    println!("РЎРЅРёРјРѕРє РіСЂР°С„Р° РїРѕСЃР»Рµ 2 РёС‚РµСЂР°С†РёР№:");
    dump(&after2.egraph, "part2_iter2");

    // Runner РіРѕРЅСЏРµС‚ РїСЂР°РІРёР»Р°, РїРѕРєР° РµСЃС‚СЊ РЅРѕРІС‹Рµ СЂР°РІРµРЅСЃС‚РІР° (РґРѕ "РЅР°СЃС‹С‰РµРЅРёСЏ").
    // РЎС‚Р°СЂС‹Рµ РІС‹СЂР°Р¶РµРЅРёСЏ РЅРµ РІС‹Р±СЂР°СЃС‹РІР°СЋС‚СЃСЏ вЂ” РѕРЅРё РѕСЃС‚Р°СЋС‚СЃСЏ РІ РіСЂР°С„Рµ.
    let runner = Runner::default().with_expr(&start).run(rules);

    println!("РСЃС…РѕРґРЅРѕРµ РІС‹СЂР°Р¶РµРЅРёРµ: {start}");
    println!(
        "РС‚РµСЂР°С†РёР№: {}, РєР»Р°СЃСЃРѕРІ СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕСЃС‚Рё: {}, СѓР·Р»РѕРІ: {}",
        runner.iterations.len(),
        runner.egraph.number_of_classes(),
        runner.egraph.total_number_of_nodes()
    );
    println!("РЎРЅРёРјРѕРє РЅР°СЃС‹С‰РµРЅРЅРѕРіРѕ РіСЂР°С„Р°:");
    dump(&runner.egraph, "part2_final");

    // Extractor РёР·РІР»РµРєР°РµС‚ РёР· РєР»Р°СЃСЃР° СЌРєРІРёРІР°Р»РµРЅС‚РЅРѕСЃС‚Рё РІС‹СЂР°Р¶РµРЅРёРµ СЃ РјРёРЅРёРјР°Р»СЊРЅРѕР№
    // СЃС‚РѕРёРјРѕСЃС‚СЊСЋ. AstSize вЂ” СЃС‚РѕРёРјРѕСЃС‚СЊ = С‡РёСЃР»Рѕ СѓР·Р»РѕРІ РґРµСЂРµРІР°.
    let extractor = Extractor::new(&runner.egraph, AstSize);
    let (cost, best) = extractor.find_best(runner.roots[0]);
    println!("РЈРїСЂРѕС‰С‘РЅРЅРѕРµ РІС‹СЂР°Р¶РµРЅРёРµ: {best} (СЃС‚РѕРёРјРѕСЃС‚СЊ {cost})");
}

